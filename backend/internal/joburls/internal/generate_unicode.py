"""Emit the two pinned urllib/str properties used by posting IDs (stdout only)."""

import hashlib
import sys
import unicodedata

assert sys.version_info[:3] == (3, 12, 14)
assert unicodedata.unidata_version == "15.0.0"

digits = bytes(int(chr(i).isdigit()) for i in range(0x110000))
delimiters = [
    i for i in range(128, 0x110000)
    if any(c in unicodedata.normalize("NFKC", chr(i)) for c in "/?#@:")
]
ranges = []
start = None
for i, flag in enumerate(digits + b"\0"):
    if flag and start is None:
        start = i
    if not flag and start is not None:
        ranges.append((start, i - 1))
        start = None

print("// Code generated by internal/generate_unicode.py; DO NOT EDIT.")
print("// Python3.12.14 / Unicode15. License: ../textcompat/ucd/LICENSE.txt.")
print("// Digit property SHA-256 (one byte per code point): " + hashlib.sha256(digits).hexdigest())
print(f"// {sum(digits)} digit code points; {len(ranges)} ranges; {len(delimiters)} NFKC delimiter code points.")
print("\npackage joburls\n")
print("var digitRanges = [...][2]rune{")
for first, last in ranges:
    print(f"\t{{0x{first:x}, 0x{last:x}}},")
print("}\n\nvar nfkcDelimiterRunes = [...]rune{")
for point in delimiters:
    print(f"\t0x{point:x},")
print("}")
