"""Emit the pinned Unicode15 printable table; no filesystem writes or reads."""

import hashlib
import sys
import unicodedata

assert sys.version_info[:3] == (3, 12, 14)
assert unicodedata.unidata_version == "15.0.0"

points = bytes(int(chr(point).isprintable()) for point in range(0x110000))
ranges = []
start = None
for point, printable in enumerate(points + b"\0"):
    if printable and start is None:
        start = point
    if not printable and start is not None:
        ranges.append((start, point - 1))
        start = None

print("// Code generated by internal/generate_printable.py; DO NOT EDIT.")
print("// Python3.12.14 / Unicode15 printable property, including ASCII space.")
print("// Unicode data license: ucd/LICENSE.txt.")
print("// SHA-256 of one printable byte per code point U+0000..U+10FFFF:")
print("// " + hashlib.sha256(points).hexdigest())
print("// Printable code points: %d; ranges: %d." % (sum(points), len(ranges)))
print("\npackage textcompat\n")
print("var printableRanges = [...][2]rune{")
for lower, upper in ranges:
    print("\t{0x%x, 0x%x}," % (lower, upper))
print("}")
