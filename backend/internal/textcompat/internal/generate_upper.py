"""Emit pinned Unicode15 uppercase/decimal mappings; no filesystem access."""

import hashlib
import json
import sys
import unicodedata

assert sys.version_info[:3] == (3, 12, 14)
assert unicodedata.unidata_version == "15.0.0"

mappings = [(point, chr(point).upper()) for point in range(0x110000)
            if chr(point).upper() != chr(point)]
decimal_zeros = [point for point in range(0x110000) if unicodedata.decimal(chr(point), -1) == 0]
payload = "".join(f"{point:x}:{upper}\n" for point, upper in mappings).encode()
print("// Code generated by internal/generate_upper.py; DO NOT EDIT.")
print("// Python3.12.14 / Unicode15; license: ucd/LICENSE.txt.")
print("// Uppercase mappings SHA-256: " + hashlib.sha256(payload).hexdigest())
print("\npackage textcompat\n")
print("var fullUpper = [...]struct { source rune; target string }{")
for point, upper in mappings:
    print(f"\t{{0x{point:x}, {json.dumps(upper, ensure_ascii=False)}}},")
print("}\n\nvar decimalZeros = [...]rune{")
for point in decimal_zeros:
    assert all(unicodedata.decimal(chr(point + digit)) == digit for digit in range(10))
    print(f"\t0x{point:x},")
print("}")
