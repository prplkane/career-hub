// Command generate mechanically regenerates the pinned Unicode table offline.
package main

import (
	"bufio"
	"bytes"
	"crypto/sha256"
	"fmt"
	"go/format"
	"os"
	"sort"
	"strconv"
	"strings"
)

const sourceHash = "cdd49e55eae3bbf1f0a3f6580c974a0263cb86a6a08daa10fbf705b4808a56f7"
const licenseHash = "e7a93b009565cfce55919a381437ac4db883e9da2126fa28b91d12732bc53d96"

func generate(raw, license []byte) ([]byte, error) {
	if fmt.Sprintf("%x", sha256.Sum256(raw)) != sourceHash || fmt.Sprintf("%x", sha256.Sum256(license)) != licenseHash {
		return nil, fmt.Errorf("pinned Unicode source or license changed")
	}
	mappings := map[int]string{}
	scanner := bufio.NewScanner(bytes.NewReader(raw))
	for scanner.Scan() {
		line := strings.TrimSpace(strings.SplitN(scanner.Text(), "#", 2)[0])
		if line == "" {
			continue
		}
		fields := strings.Split(line, ";")
		if len(fields) != 4 {
			return nil, fmt.Errorf("invalid source record")
		}
		status := strings.TrimSpace(fields[1])
		if status != "C" && status != "F" {
			continue
		}
		source, err := strconv.ParseInt(strings.TrimSpace(fields[0]), 16, 32)
		if err != nil || source < 0 || source > 0x10ffff || (source >= 0xd800 && source <= 0xdfff) {
			return nil, fmt.Errorf("invalid source scalar")
		}
		if _, exists := mappings[int(source)]; exists {
			return nil, fmt.Errorf("duplicate full fold")
		}
		var target strings.Builder
		for _, point := range strings.Fields(fields[2]) {
			value, err := strconv.ParseInt(point, 16, 32)
			if err != nil || value < 0 || value > 0x10ffff || (value >= 0xd800 && value <= 0xdfff) {
				return nil, fmt.Errorf("invalid target scalar")
			}
			target.WriteRune(rune(value))
		}
		if target.Len() == 0 {
			return nil, fmt.Errorf("empty full fold")
		}
		mappings[int(source)] = target.String()
	}
	if err := scanner.Err(); err != nil {
		return nil, err
	}
	if len(mappings) != 1530 {
		return nil, fmt.Errorf("unexpected full-fold count")
	}
	keys := make([]int, 0, len(mappings))
	for key := range mappings {
		keys = append(keys, key)
	}
	sort.Ints(keys)
	var out bytes.Buffer
	out.WriteString("// Code generated by go generate; DO NOT EDIT.\n")
	out.WriteString("// Unicode15 default full case folds; source data copyright 2022 Unicode, Inc.\n")
	out.WriteString("// Distributed under Unicode License v3; see ucd/LICENSE.txt.\n")
	fmt.Fprintf(&out, "// Source SHA-256: %s\n\npackage textcompat\n\n", sourceHash)
	out.WriteString("type foldEntry struct { source rune; target string }\n\nvar fullFolds = [...]foldEntry{\n")
	for _, key := range keys {
		fmt.Fprintf(&out, "{0x%04x, %s},\n", key, strconv.QuoteToASCII(mappings[key]))
	}
	out.WriteString("}\n")
	return format.Source(out.Bytes())
}

func run() error {
	raw, err := os.ReadFile("ucd/CaseFolding-15.0.0.txt")
	if err != nil {
		return err
	}
	license, err := os.ReadFile("ucd/LICENSE.txt")
	if err != nil {
		return err
	}
	generated, err := generate(raw, license)
	if err != nil {
		return err
	}
	// Only the named generated source in this package is a regeneration target.
	return os.WriteFile("tables_generated.go", generated, 0o644)
}

func main() {
	if err := run(); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}
