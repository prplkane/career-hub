"""Emit Python3.12/Unicode15 analysis properties; no filesystem I/O."""
import hashlib
import sys
import unicodedata

assert sys.version_info[:3] == (3, 12, 14)
assert unicodedata.unidata_version == "15.0.0"
values = bytes((int(unicodedata.category(chr(p)) != "Cn")
                | (2 if chr(p).isalnum() or p == 95 else 0)
                | (4 if chr(p).isupper() else 0)
                | (8 if chr(p).islower() or unicodedata.category(chr(p)) == "Lt" else 0))
               for p in range(0x110000))
ranges=[]
start=0
for point in range(1,len(values)+1):
    if point==len(values) or values[point]!=values[start]:
        if values[start]: ranges.append((start,point-1,values[start]))
        start=point
print("// Code generated by internal/generate_analysis_properties.py; DO NOT EDIT.")
print("// Python3.12.14 / Unicode15; license: ucd/LICENSE.txt.")
print("// Property bytes SHA-256: "+hashlib.sha256(values).hexdigest())
print(f"// Nonzero ranges: {len(ranges)}.")
print("\npackage textcompat\n\nvar analysisRanges = [... ]struct{ first, last rune; flags byte }{")
for first,last,flags in ranges: print(f"\t{{0x{first:x},0x{last:x},{flags}}},")
print("}")
