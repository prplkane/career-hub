"""Print pinned mark ranges to stdout; the maintainer applies the reviewed output."""
import hashlib
import sys
import unicodedata

assert sys.version_info[:3] == (3, 12, 14)
assert unicodedata.unidata_version == "15.0.0"
values = bytes(unicodedata.category(chr(p)).startswith("M") for p in range(0x110000))
ranges = []
start = 0
for point in range(1, len(values) + 1):
    if point == len(values) or values[point] != values[start]:
        if values[start]:
            ranges.append((start, point - 1))
        start = point
print("// Code generated by internal/generate_mark.py; DO NOT EDIT.")
print("// Python3.12.14 / Unicode15; license: ucd/LICENSE.txt.")
print("// Property bytes SHA-256: " + hashlib.sha256(values).hexdigest())
print("\npackage textcompat\n\nvar markRanges = [...][2]rune{")
for first, last in ranges:
    print(f"\t{{0x{first:x}, 0x{last:x}}},")
print("}")
