"""Emit pinned full lower/title mappings and contextual casing; stdout only.

Python does not expose Case_Ignorable directly. The two minimal Final_Sigma
contexts independently observe it, including characters that are both cased
and ignorable. No Go table or target algorithm supplies these observations.
"""
import hashlib
import json
import sys
import unicodedata

assert sys.version_info[:3] == (3, 12, 14)
assert unicodedata.unidata_version == "15.0.0"

print("// Code generated by internal/generate_case.py; DO NOT EDIT.")
print("// Python3.12.14 / Unicode15; license: ucd/LICENSE.txt.")
print("\npackage textcompat\n")

for operation in ("lower", "title"):
    pairs = [(p, getattr(chr(p), operation)()) for p in range(0x110000)
             if getattr(chr(p), operation)() != chr(p)]
    payload = "".join(f"{p:x}:{value}\n" for p, value in pairs).encode()
    print(f"// {operation} mappings SHA-256: {hashlib.sha256(payload).hexdigest()}")
    singles = [(p, ord(value) - p) for p, value in pairs if len(value) == 1]
    ranges, index = [], 0
    while index < len(singles):
        first, delta = singles[index]
        last, step = first, 1
        if index + 1 < len(singles):
            distance = singles[index + 1][0] - first
            if distance in (1, 2) and singles[index + 1][1] == delta:
                step = distance
        index += 1
        while index < len(singles) and singles[index] == (last + step, delta):
            last = singles[index][0]
            index += 1
        ranges.append((first, last, step, delta))
    print(f"var {operation}Ranges = [...]caseRange{{")
    for first, last, step, delta in ranges:
        print(f" {{0x{first:x}, 0x{last:x}, {step}, {delta}}},")
    print("}")
    print(f"var {operation}Expansions = [...]caseExpansion{{")
    for p, value in pairs:
        if len(value) != 1:
            print(f" {{0x{p:x}, {json.dumps(value, ensure_ascii=False)}}},")
    print("}\n")

ignorable = bytes(int(("A" + chr(p) + "Σ").lower().endswith("ς")
                      and not ("-" + chr(p) + "Σ").lower().endswith("ς"))
                  for p in range(0x110000))
print("// Case_Ignorable bytes SHA-256: " + hashlib.sha256(ignorable).hexdigest())
print("var caseIgnorableRanges = [...][2]rune{")
first = None
for p in range(len(ignorable) + 1):
    active = p < len(ignorable) and ignorable[p]
    if active and first is None:
        first = p
    elif not active and first is not None:
        print(f" {{0x{first:x}, 0x{p-1:x}}},")
        first = None
print("}")
