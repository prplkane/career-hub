"""Emit Python3.12.14/Unicode15 isalpha ranges; no filesystem I/O."""
import hashlib
import sys
import unicodedata

assert sys.version_info[:3] == (3, 12, 14)
assert unicodedata.unidata_version == "15.0.0"
points = bytes(int(chr(point).isalpha()) for point in range(0x110000))
ranges, start = [], None
for point, matched in enumerate(points + b"\0"):
    if matched and start is None:
        start = point
    if not matched and start is not None:
        ranges.append((start, point - 1))
        start = None
print("// Code generated by internal/generate_alpha.py; DO NOT EDIT.")
print("// Python3.12.14 / Unicode15; license: ucd/LICENSE.txt.")
print("// isalpha bytes SHA-256: " + hashlib.sha256(points).hexdigest())
print(f"// Matched code points: {sum(points)}; ranges: {len(ranges)}.")
print("\npackage textcompat\n\nvar alphaRanges = [...][2]rune{")
for first, last in ranges:
    print(f"\t{{0x{first:x}, 0x{last:x}}},")
print("}")
