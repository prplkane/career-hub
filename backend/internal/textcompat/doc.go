// Package textcompat pins the Unicode 15 text semantics that existing skill
// identities depend on. It is not linguistic or fuzzy matching, not Unicode
// security normalization and not input validation: inputs must be valid
// UTF-8 scalar strings, validated at the decoding boundary. Changing the
// Unicode contract requires a reviewed identity and revision migration.
//
// Fold applies full case folding (C+F mappings); Strip trims the 29 Unicode
// whitespace characters; Normalize folds, splits on that whitespace and
// joins with ASCII space. None applies NFC, NFKC, accent removal, locale
// casing or punctuation changes, so composed and decomposed accents stay
// distinct. IsSpace, IsPrintable, IsWord, IsUpperString, IsMark,
// DecimalDigit, Upper, Lower, Title and SplitLines expose the corresponding
// Unicode 15 properties and full-case mappings (Title starts a new word at a
// combining mark or apostrophe; final sigma context skips Case_Ignorable
// characters). NFKC15 is a bounded normalizer for complete-JD fingerprints
// only; it rejects invalid UTF-8, a changed normalization data version and
// its memory and output budgets, and leaves post-Unicode-15 assignments
// opaque.
//
// The fold table in tables_generated.go is generated by go generate from
// ucd/CaseFolding-15.0.0.txt (hash-checked, 1530 non-identity mappings). The
// other property tables are generated by the scripts under internal/ from
// the Unicode 15 character database and reviewed into *_generated.go; tests
// recompute exhaustive per-scalar fingerprints for each. The Unicode data is
// used under ucd/LICENSE.txt, which must accompany any distributed binary
// that embeds these tables. Helpers keep no mutable shared state.
