package protocol

import (
	"encoding/base64"
	"errors"
	"io"
)

const (
	Version        = 1
	MaxRecordBytes = 8 * 1024
	MaxPathChars   = 4096
)

// Error is a stable, content-free protocol failure. Underlying I/O errors are
// returned separately; a future process adapter must sanitize them before output.
type Error struct{ Code string }

func (e *Error) Error() string  { return e.Code }
func failure(code string) error { return &Error{Code: code} }

// CompatibilityError reports a known unimplemented Python behavior. It must not
// be counted as parity or emitted as a fabricated Python protocol error code.
type CompatibilityError struct{ Reason string }

func (e *CompatibilityError) Error() string { return "sidecar compatibility unsupported: " + e.Reason }

// ReadRecord consumes at most MaxRecordBytes+2 bytes, through the first newline.
// No buffering is retained or allowed to consume bytes from the next record.
// Like the Python primitive it has no timeout; lifecycle owns cancellation.
func ReadRecord(stream io.Reader) (map[string]any, error) {
	line := make([]byte, 0, MaxRecordBytes+2)
	var one [1]byte
	for len(line) < MaxRecordBytes+2 {
		_, err := io.ReadFull(stream, one[:])
		if err != nil {
			if !errors.Is(err, io.EOF) {
				return nil, err
			}
			break
		}
		line = append(line, one[0])
		if one[0] == '\n' {
			break
		}
	}
	if len(line) == 0 {
		return nil, failure("SIDECAR_PIPE_CLOSED")
	}
	if line[len(line)-1] != '\n' {
		if len(line) > MaxRecordBytes {
			return nil, failure("SIDECAR_RECORD_TOO_LARGE")
		}
		return nil, failure("SIDECAR_RECORD_TRUNCATED")
	}
	line = line[:len(line)-1]
	if len(line) > 0 && line[len(line)-1] == '\r' {
		line = line[:len(line)-1]
	}
	if len(line) > MaxRecordBytes {
		return nil, failure("SIDECAR_RECORD_TOO_LARGE")
	}
	return decodeObject(line)
}

// WriteRecord writes one complete LF-terminated record, then flushes when the
// supplied writer exposes Flush() error. Unbuffered Go writers need no flush.
func WriteRecord(stream io.Writer, payload map[string]any) error {
	encoded, err := EncodeRecord(payload)
	if err != nil {
		return err
	}
	n, err := stream.Write(encoded)
	if err != nil {
		return err
	}
	if n != len(encoded) {
		return io.ErrShortWrite
	}
	if flusher, ok := stream.(interface{ Flush() error }); ok {
		return flusher.Flush()
	}
	return nil
}

type StartRecord struct {
	Port         int    `json:"port"`
	ResourceRoot string `json:"resource_root"`
	DataRoot     string `json:"data_root"`
	Channel      string `json:"channel"`
	// SessionToken is the desktop window's capability token, generated by the
	// Electron host and passed here over the owned stdin pipe (ADR SEC-250).
	// It is never echoed in any record. Empty when the host omitted it.
	SessionToken string `json:"-"`
}

func exactFields(payload map[string]any, fields ...string) bool {
	if len(payload) != len(fields) {
		return false
	}
	for _, field := range fields {
		if _, found := payload[field]; !found {
			return false
		}
	}
	return true
}

// ParseStart preserves fields -> version -> command -> port -> channel ->
// resource_root -> data_root validation order. Path checks are lexical only.
func ParseStart(payload map[string]any, paths PathOptions) (StartRecord, error) {
	var start StartRecord
	base := []string{"command", "protocol_version", "port", "resource_root", "data_root", "channel"}
	_, hasToken := payload["session_token"]
	if hasToken && !exactFields(payload, append(base, "session_token")...) || !hasToken && !exactFields(payload, base...) {
		return start, failure("SIDECAR_RECORD_INVALID_FIELDS")
	}
	if !integerEquals(payload["protocol_version"], Version) {
		return start, failure("SIDECAR_PROTOCOL_UNSUPPORTED")
	}
	if command, ok := payload["command"].(string); !ok || command != "start" {
		return start, failure("SIDECAR_COMMAND_UNSUPPORTED")
	}
	if !integerEquals(payload["port"], 0) {
		return start, failure("SIDECAR_START_INVALID_PORT")
	}
	channel, ok := payload["channel"].(string)
	if !ok || (channel != "dev" && channel != "stable") {
		return start, failure("SIDECAR_START_INVALID_CHANNEL")
	}
	resource, err := absolutePath(payload["resource_root"], paths)
	if err != nil {
		return start, err
	}
	data, err := absolutePath(payload["data_root"], paths)
	if err != nil {
		return start, err
	}
	token := ""
	if hasToken {
		var ok bool
		if token, ok = validSessionToken(payload["session_token"]); !ok {
			return start, failure("SIDECAR_START_INVALID_TOKEN")
		}
	}
	return StartRecord{Port: 0, ResourceRoot: resource, DataRoot: data, Channel: channel, SessionToken: token}, nil
}

// validSessionToken decides whether the host-supplied session_token is
// acceptable. It returns the token and true only for a well-formed value; any
// doubt must return false, which refuses startup (fail closed). The value is a
// secret: never include it in an error, log or record.
func validSessionToken(raw any) (string, bool) {
	token, isString := raw.(string)
	if !isString {
		return "", false
	}
	decoded, err := base64.RawURLEncoding.DecodeString(token)
	if err != nil || len(decoded) != 32 {
		return "", false
	}
	// A lenient decoder ignores the last character's unused bits, so different
	// spellings can decode to the same bytes. Only the canonical spelling,
	// which re-encodes identically, is accepted.
	if base64.RawURLEncoding.EncodeToString(decoded) != token {
		return "", false
	}
	return token, true
}

func ParseShutdown(payload map[string]any) error {
	if !exactFields(payload, "command", "protocol_version") {
		return failure("SIDECAR_RECORD_INVALID_FIELDS")
	}
	if !integerEquals(payload["protocol_version"], Version) {
		return failure("SIDECAR_PROTOCOL_UNSUPPORTED")
	}
	if command, ok := payload["command"].(string); !ok || command != "shutdown" {
		return failure("SIDECAR_COMMAND_UNSUPPORTED")
	}
	return nil
}

// Record helpers intentionally do not add validation absent from Python.
// appVersion is injected by the composition root; this package reads no VERSION.
func ReadyRecord(appVersion string, port int, channel string) map[string]any {
	return map[string]any{"event": "ready", "protocol_version": Version, "app_version": appVersion, "port": port, "channel": channel}
}

func HealthRecord(appVersion string) map[string]any {
	return map[string]any{"status": "ok", "protocol_version": Version, "app_version": appVersion}
}

func ErrorRecord(code string) map[string]any {
	return map[string]any{"event": "error", "protocol_version": Version, "error_code": code}
}
