  function readPreference() {
    try {
      const storedPreference = window.localStorage.getItem(storageKey);
      return preferences.has(storedPreference) ? storedPreference : "system";
    } catch (_error) {
      return "system";
    }
  }

  function systemLocale() {
    const languages = Array.isArray(navigator.languages) && navigator.languages.length
      ? navigator.languages
      : [navigator.language || "en"];
    return languages.some((language) => String(language).toLocaleLowerCase().startsWith("ru"))
      ? "ru"
      : "en";
  }

  function resolveLocale(preference) {
    return preference === "system" ? systemLocale() : preference;
  }

  function storePreference(preference) {
    try {
      window.localStorage.setItem(storageKey, preference);
    } catch (_error) {
      // The selected language still applies to this page when storage is unavailable.
    }
  }

  function translateCore(value, locale = resolvedLocale) {
    if (locale !== "ru" || !value) return value;
    if (Object.hasOwn(RU_TEXT, value)) return RU_TEXT[value];
    for (const [pattern, replacement] of RU_PATTERNS) {
      if (pattern.test(value)) return value.replace(pattern, replacement);
    }
    if (value.includes(" | ")) {
      return value.split(" | ").map((part) => translateCore(part, locale)).join(" | ");
    }
    return value;
  }

  function translateString(value, locale = resolvedLocale) {
    const text = String(value ?? "");
    const leading = text.match(/^\s*/)?.[0] || "";
    const trailing = text.match(/\s*$/)?.[0] || "";
    const coreEnd = trailing ? text.length - trailing.length : text.length;
    const core = text.slice(leading.length, coreEnd);
    return `${leading}${translateCore(core, locale)}${trailing}`;
  }

  function isIgnored(node) {
    const element = node.nodeType === Node.ELEMENT_NODE ? node : node.parentElement;
    return Boolean(element?.closest(
      `script, style, code, pre, samp, [translate='no'], [data-locale-ignore], ${canonicalContentSelector}`,
    ));
  }

  function localizeTextNode(node) {
    if (!node?.data || node.parentElement?.matches("textarea") || isIgnored(node)) return;
    const current = node.data;
    const priorTranslation = translatedText.get(node);
    if (resolvedLocale === "ru") {
      if (current === priorTranslation) return;
      const translated = translateString(current, "ru");
      if (translated === current) return;
      originalText.set(node, current);
      translatedText.set(node, translated);
      node.data = translated;
      return;
    }
    if (!originalText.has(node)) return;
    if (current === priorTranslation) node.data = originalText.get(node);
    originalText.delete(node);
    translatedText.delete(node);
  }

  function attributeState(element) {
    let state = originalAttributes.get(element);
    if (!state) {
      state = new Map();
      originalAttributes.set(element, state);
    }
    return state;
  }

  function localizeAttribute(element, attribute) {
    if (!element.hasAttribute(attribute) || isIgnored(element)) return;
    const current = element.getAttribute(attribute) || "";
    const state = attributeState(element);
    const prior = state.get(attribute);
    if (resolvedLocale === "ru") {
      if (current === prior?.translated) return;
      const translated = translateString(current, "ru");
      if (translated === current) return;
      state.set(attribute, { original: current, translated });
      element.setAttribute(attribute, translated);
      return;
    }
    if (!prior) return;
    if (current === prior.translated) element.setAttribute(attribute, prior.original);
    state.delete(attribute);
  }

  function localizeSubtree(root) {
    if (!root) return;
    if (root.nodeType === Node.TEXT_NODE) {
      localizeTextNode(root);
      return;
    }
    if (root.nodeType !== Node.ELEMENT_NODE && root.nodeType !== Node.DOCUMENT_NODE) return;
    if (root.nodeType === Node.ELEMENT_NODE) {
      translatableAttributes.forEach((attribute) => localizeAttribute(root, attribute));
    }
    const walker = document.createTreeWalker(root, NodeFilter.SHOW_ELEMENT | NodeFilter.SHOW_TEXT);
    let node = walker.nextNode();
    while (node) {
      if (node.nodeType === Node.TEXT_NODE) {
        localizeTextNode(node);
      } else {
        translatableAttributes.forEach((attribute) => localizeAttribute(node, attribute));
      }
      node = walker.nextNode();
    }
  }

  function flushScheduledTranslations() {
    translationScheduled = false;
    const roots = [...scheduledRoots];
    scheduledRoots = new Set();
    roots.forEach((root) => localizeSubtree(root));
  }

  function scheduleTranslation(root) {
    if (!root) return;
    scheduledRoots.add(root);
    if (translationScheduled) return;
    translationScheduled = true;
    queueMicrotask(flushScheduledTranslations);
  }

  function startObserver() {
    observer?.disconnect();
    observer = new MutationObserver((mutations) => {
      mutations.forEach((mutation) => {
        if (mutation.type === "childList") {
          mutation.addedNodes.forEach((node) => scheduleTranslation(node));
        } else {
          scheduleTranslation(mutation.target);
        }
      });
    });
    observer.observe(document.documentElement, {
      attributes: true,
      attributeFilter: translatableAttributes,
      characterData: true,
      childList: true,
      subtree: true,
    });
  }

  function applyPreference(preference, { notify = true } = {}) {
    activePreference = preferences.has(preference) ? preference : "system";
    resolvedLocale = resolveLocale(activePreference);
    document.documentElement.dataset.localePreference = activePreference;
    document.documentElement.dataset.locale = resolvedLocale;
    document.documentElement.lang = resolvedLocale;
    if (document.body) localizeSubtree(document.documentElement);
    if (notify && document.body) {
      window.dispatchEvent(new CustomEvent("careerhub:localechange", {
        detail: { locale: resolvedLocale, preference: activePreference },
      }));
    }
  }

  applyPreference(readPreference(), { notify: false });
  if (resolvedLocale === "ru") document.documentElement.dataset.localePending = "true";

